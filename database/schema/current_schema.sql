-- =============================================================
-- AUST ROBOTICS CLUB - CENTRAL MODULAR DATABASE
-- Target: Neon PostgreSQL / PostgreSQL 15+
-- Converted from the AUSTRC MySQL 8.0 baseline.
-- Uses PostgreSQL IDENTITY, JSONB, TIMESTAMPTZ, CREATE INDEX, and update triggers.
-- Purpose: ERD generation + implementation baseline
-- Modules:
--   1) SHARED / CORE     -> core_* and infra_*
--   2) EVENT MANAGEMENT -> evt_*
--   3) ADMINISTRATION   -> adm_*
--
-- Architectural rule:
--   evt_* and adm_* may reference core_* / infra_*.
--   core_* / infra_* NEVER reference evt_* or adm_* with FKs.
--   evt_* and adm_* do not directly reference each other.
-- =============================================================

