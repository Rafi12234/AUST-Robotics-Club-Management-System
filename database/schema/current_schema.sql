-- =============================================================
-- POSTGRESQL AUTOMATIC updated_at SUPPORT
-- MySQL's "ON UPDATE CURRENT_TIMESTAMP" does not exist in PostgreSQL.
-- This reusable trigger preserves the same behavior.
-- =============================================================

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_core_users_set_updated_at
BEFORE UPDATE ON core_users
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_infra_files_set_updated_at
BEFORE UPDATE ON infra_files
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_core_user_profiles_set_updated_at
BEFORE UPDATE ON core_user_profiles
FOR EACH ROW
